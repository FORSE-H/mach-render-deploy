"""Seeds — the trusted human-provided minimum for an entry.

A seed is the only thing MACH trusts as input: identifier, name, url,
code_repository, category. Everything else about an entry is regenerated by
harvesters with lineage.

The permanent seed list lives in a human-editable CSV (data/seeds.csv), fed over
time by the entry-proposal pipeline. `read_seeds_csv` is the durable load path
used to (re)build the catalogue. Bootstrapping that CSV from the legacy JSON-LD
files is a one-time migration and lives in scripts/bootstrap_seeds.py, not here.
"""

from __future__ import annotations

import csv
from pathlib import Path

from pydantic import BaseModel

SEED_COLUMNS = ("identifier", "name", "url", "code_repository", "category")


class Seed(BaseModel):
    identifier: str
    name: str
    url: str
    code_repository: str | None = None
    category: str


def read_seeds_csv(path: Path) -> list[Seed]:
    """Load seeds from the durable CSV. Blank code_repository becomes None."""
    with path.open(encoding="utf-8", newline="") as f:
        return [
            Seed(
                identifier=row["identifier"],
                name=row["name"],
                url=row["url"],
                code_repository=row.get("code_repository") or None,
                category=row["category"],
            )
            for row in csv.DictReader(f)
        ]
